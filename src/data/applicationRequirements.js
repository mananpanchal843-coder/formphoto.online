export const searchApplications = (query, category = null) => {
  const q = (query || '').trim().toLowerCase();
  return APPLICATIONS.filter((a) => {
    if (category && a.category !== category) return false;
    if (!q) return true;
    const hay = `${a.name} ${a.organization} ${a.id} ${a.category}`.toLowerCase();
    return hay.includes(q);
  });
};

